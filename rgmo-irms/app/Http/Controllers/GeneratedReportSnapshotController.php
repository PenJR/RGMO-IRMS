<?php

namespace App\Http\Controllers;

use App\Models\ForecastSnapshotExplanation;
use App\Models\GeneratedReportSnapshot;
use Barryvdh\DomPDF\Facade\Pdf;
use Illuminate\Http\Request;
use Illuminate\Validation\Rule;

class GeneratedReportSnapshotController extends Controller
{
    public function index(Request $request)
    {
        $this->authorize('viewAny', GeneratedReportSnapshot::class);
        $reportTypes = GeneratedReportSnapshot::reportTypesFor($request->user());
        $filters = $request->validate([
            'search' => ['nullable', 'string', 'max:255'],
            'report_key' => ['nullable', Rule::in(array_keys($reportTypes))],
            'generator' => ['nullable', 'string', 'max:255'],
            'start_date' => ['nullable', 'date_format:Y-m-d'],
            'end_date' => ['nullable', 'date_format:Y-m-d', ...($request->filled('start_date') ? ['after_or_equal:start_date'] : [])],
        ]);
        $query = GeneratedReportSnapshot::query()->accessibleTo($request->user());
        if (! empty($filters['search'])) {
            $term = '%'.trim($filters['search']).'%';
            $query->where(function ($query) use ($term) {
                $query->where('title', 'like', $term)->orWhere('id', 'like', $term);
            });
        }
        if (! empty($filters['report_key'])) {
            $query->where('report_key', $filters['report_key']);
        }
        if (! empty($filters['generator'])) {
            $query->where('generator_name', 'like', '%'.trim($filters['generator']).'%');
        }
        if (! empty($filters['start_date'])) {
            $query->whereDate('generated_at', '>=', $filters['start_date']);
        }
        if (! empty($filters['end_date'])) {
            $query->whereDate('generated_at', '<=', $filters['end_date']);
        }
        $snapshots = $query->orderByDesc('generated_at')->orderByDesc('id')->paginate(20)->withQueryString();

        return view('reports.history.index', compact('snapshots', 'filters', 'reportTypes'));
    }

    public function show(GeneratedReportSnapshot $snapshot)
    {
        $this->authorize('view', $snapshot);

        return view('reports.history.show', $this->presentationData($snapshot));
    }

    public function pdf(GeneratedReportSnapshot $snapshot)
    {
        $this->authorize('view', $snapshot);
        $maxColumns = max(array_map(fn (array $section) => count($section['columns']), $snapshot->snapshot['sections']));

        return Pdf::loadView('reports.history.pdf', $this->presentationData($snapshot))
            ->setPaper($maxColumns > 12 ? 'a3' : 'a4', 'landscape')
            ->setOptions(['isRemoteEnabled' => false])
            ->download($snapshot->downloadFilename('pdf'));
    }

    public function csv(GeneratedReportSnapshot $snapshot)
    {
        $this->authorize('view', $snapshot);
        $data = $this->presentationData($snapshot);

        return response()->streamDownload(function () use ($snapshot, $data): void {
            $handle = fopen('php://output', 'w');
            // UTF-8 BOM keeps captured names and currency symbols readable in spreadsheets.
            fwrite($handle, "\xEF\xBB\xBF");
            $write = function (array $row) use ($handle): void {
                fputcsv($handle, array_map(fn ($value) => $this->csvCell($value), $row), ',', '"', '');
            };
            $write(['Report', $snapshot->title]);
            $write(['Snapshot ID', $snapshot->id]);
            $write(['Generated at', $snapshot->generated_at->toIso8601String()]);
            $write(['Generated by', $snapshot->generator_name]);
            foreach ($data['savedFilters'] as $key => $value) {
                $write(['Filter: '.$key, is_array($value) ? json_encode($value, JSON_UNESCAPED_UNICODE) : $value]);
            }
            foreach ($data['savedMetadata'] as $key => $value) {
                $write(['Metadata: '.$key, $value]);
            }
            $write([]);
            foreach ($snapshot->snapshot['summary'] as $summary) {
                $write([$summary['label'], $summary['value']]);
            }
            foreach ($snapshot->snapshot['sections'] as $section) {
                $write([]);
                $write([$section['title']]);
                $write(array_column($section['columns'], 'label'));
                foreach ($section['rows'] as $row) {
                    $write(array_map(fn (array $column) => $row[$column['key']], $section['columns']));
                }
            }
            if ($brief = $data['savedAiBrief']) {
                $write([]);
                $write(['Saved AI brief']);
                $write(['AI brief generated at', $brief->generated_at->toIso8601String()]);
                $write(['AI brief generated by', $brief->generator_name]);
                $write(['Summary', $brief->explanation['summary']]);
                foreach ($brief->explanation['priorities'] as $priority) {
                    $write(['Priority', $priority]);
                }
                foreach ($brief->explanation['warnings'] as $warning) {
                    $write(['Warning', $warning]);
                }
            }
            fclose($handle);
        }, $snapshot->downloadFilename('csv'), ['Content-Type' => 'text/csv; charset=UTF-8']);
    }

    public function json(GeneratedReportSnapshot $snapshot)
    {
        $this->authorize('view', $snapshot);
        $brief = $this->savedAiBrief($snapshot);

        return response()->json([
            'id' => $snapshot->id,
            'report_key' => $snapshot->report_key,
            'title' => $snapshot->title,
            'generated_by' => $snapshot->generator_name,
            'generated_at' => $snapshot->generated_at->toIso8601String(),
            'schema_version' => $snapshot->schema_version,
            'filters' => $snapshot->filters,
            'snapshot' => $snapshot->snapshot,
            'saved_ai_brief' => $brief ? [
                'generated_at' => $brief->generated_at->toIso8601String(),
                'generated_by' => $brief->generator_name,
                'provider' => $brief->provider,
                'model' => $brief->model,
                'explanation' => $brief->explanation,
            ] : null,
        ], 200, [
            'Content-Disposition' => 'attachment; filename="'.$snapshot->downloadFilename('json').'"',
        ], JSON_PRETTY_PRINT | JSON_UNESCAPED_UNICODE);
    }

    private function presentationData(GeneratedReportSnapshot $snapshot): array
    {
        $metadata = $snapshot->snapshot['metadata'];
        $savedMetadata = array_filter($metadata, fn ($value) => ! is_array($value));
        if (is_array($metadata['currency'] ?? null)) {
            $currency = $metadata['currency'];
            $savedMetadata['currency'] = trim(($currency['code'] ?? '').' '.($currency['symbol'] ?? ''));
        }
        $savedFilters = $snapshot->filters;
        foreach ($metadata['filter_labels'] ?? [] as $key => $label) {
            if (array_key_exists($key, $savedFilters) && is_string($label) && $label !== '') {
                $savedFilters[$key] = $label.' (ID: '.$savedFilters[$key].')';
            }
        }

        return [
            'snapshot' => $snapshot,
            'savedMetadata' => $savedMetadata,
            'savedFilters' => $savedFilters,
            'savedAiBrief' => $this->savedAiBrief($snapshot),
        ];
    }

    private function savedAiBrief(GeneratedReportSnapshot $snapshot): ?ForecastSnapshotExplanation
    {
        return $snapshot->report_key === 'forecast' ? ForecastSnapshotExplanation::find($snapshot->id) : null;
    }

    private function csvCell(mixed $value): mixed
    {
        if (is_bool($value)) {
            return $value ? 'Yes' : 'No';
        }
        if (is_string($value) && preg_match('/^[\s]*[=+\-@]/u', $value)) {
            return "'".$value;
        }

        return $value;
    }
}
